#!/usr/bin/env node
// Builds dist/ClaudeBridge-<version>.zip: ClaudeBridge.exe (Node with the bridge
// built in, so players don't need Node) plus the addon folder it installs.
//
//   node scripts/build-exe.js [version]      e.g. v1.0.0 (default: dev)
//
// Windows only: the exe is this machine's node.exe with the bridge injected
// as a Node single executable application (https://nodejs.org/api/single-executable-applications.html).
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const DIST = path.join(ROOT, 'dist');
const MODULES = ['paths', 'lock', 'protocol', 'waypoint-mcp', 'setup', 'bridge', 'cli'];
const FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2';

// A single executable runs one script that can only require Node's built-ins,
// so the bridge's own files are bundled into one, each in a CommonJS-style
// wrapper with a require() that resolves './name' to the bundled module.
function bundle(version) {
  const mods = MODULES.map((name) => {
    const src = fs.readFileSync(path.join(ROOT, 'bridge', `${name}.js`), 'utf8').replace(/^#!.*\n/, '');
    return `${JSON.stringify(name)}: function (module, exports, require, __filename, __dirname) {\n${src}\n}`;
  });
  mods.push(`"version": function (module) { module.exports = ${JSON.stringify(version)}; }`);
  return [
    '// Generated by scripts/build-exe.js. Do not edit.',
    '"use strict";',
    `const __mods = {\n${mods.join(',\n')}\n};`,
    'const __cache = {};',
    'const __builtin = require;',
    'function __require(id) {',
    "  if (!id.startsWith('./')) return __builtin(id);",
    "  const name = id.slice(2).replace(/\\.js$/, '');",
    '  if (!__mods[name]) throw new Error(`Not bundled: ${id}`);',
    '  if (!__cache[name]) {',
    '    const module = { exports: {} };',
    '    __cache[name] = module;',
    "    __mods[name].call(module.exports, module, module.exports, __require, name + '.js', 'bridge');",
    '  }',
    '  return __cache[name].exports;',
    '}',
    "__require('./cli');",
    '',
  ].join('\n');
}

function run(cmd, args) {
  execFileSync(cmd, args, { stdio: 'inherit', cwd: ROOT, shell: cmd === 'npx' });
}

function build(version) {
  if (process.platform !== 'win32') throw new Error('ClaudeBridge.exe has to be built on Windows.');
  fs.rmSync(DIST, { recursive: true, force: true });
  const stage = path.join(DIST, 'ClaudeBridge');
  fs.mkdirSync(stage, { recursive: true });

  fs.writeFileSync(path.join(DIST, 'bundle.js'), bundle(version));
  fs.writeFileSync(path.join(DIST, 'sea-config.json'), JSON.stringify({
    main: path.join(DIST, 'bundle.js'),
    output: path.join(DIST, 'sea-prep.blob'),
    disableExperimentalSEAWarning: true,
    useCodeCache: false,
    useSnapshot: false,
  }, null, 2));
  run(process.execPath, ['--experimental-sea-config', path.join(DIST, 'sea-config.json')]);

  const exe = path.join(stage, 'ClaudeBridge.exe');
  fs.copyFileSync(process.execPath, exe);
  run('npx', ['--yes', 'postject@1.0.0-alpha.6', `"${exe}"`, 'NODE_SEA_BLOB', `"${path.join(DIST, 'sea-prep.blob')}"`, '--sentinel-fuse', FUSE]);

  fs.cpSync(path.join(ROOT, 'addon', 'ClaudeBridge'), path.join(stage, 'addon', 'ClaudeBridge'), { recursive: true });
  fs.writeFileSync(path.join(stage, 'README.txt'), [
    `Claude Bridge ${version}: ask Claude questions from inside WoW: Forever.`,
    '',
    'Needs Claude Code installed and logged in on this PC: https://claude.com/claude-code',
    '(run "claude" in a terminal once and log in).',
    '',
    '1. Keep ClaudeBridge.exe and the addon folder together in a folder of their own.',
    '2. Double-click ClaudeBridge.exe. The first time it finds WoW and installs the addon;',
    '   if WoW is open, quit it fully and start it again.',
    '3. Leave the window open while you play. In game, type /claude.',
    '',
    'Settings and the conversation are kept next to the exe (config.json, state.json, agent-home).',
    'To reinstall the addon: ClaudeBridge.exe setup. To remove it: ClaudeBridge.exe setup --uninstall.',
    '',
  ].join('\r\n'));

  const zip = path.join(DIST, `ClaudeBridge-${version}.zip`);
  run('powershell', ['-NoProfile', '-Command', `Compress-Archive -Path "${stage}\\*" -DestinationPath "${zip}" -Force`]);
  console.log(`Built ${zip}`);
}

module.exports = { bundle };

if (require.main === module) build(process.argv[2] || process.env.CB_VERSION || 'dev');
